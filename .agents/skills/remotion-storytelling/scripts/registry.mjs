import fs from "node:fs";
import path from "node:path";
import {randomUUID} from "node:crypto";

export function validateSlug(value, label = "slug") {
  if (typeof value !== "string" || !/^[a-z0-9]+(?:-[a-z0-9]+)*$/.test(value)) {
    throw new Error("Invalid " + label + ": use lowercase letters, digits, and single hyphens.");
  }
  return value;
}

function directories(parent) {
  if (!fs.existsSync(parent)) return [];
  return fs.readdirSync(parent, {withFileTypes: true})
    .filter(entry => entry.isDirectory())
    .map(entry => entry.name).sort();
}

export function partFiles(episodeDir) {
  const folder = path.join(episodeDir, "parts");
  const parts = fs.readdirSync(folder, {withFileTypes: true})
    .filter(entry => entry.isFile())
    .flatMap(({name}) => {
      const match = /^Part(\d+)[A-Za-z0-9]*\.tsx$/.exec(name);
      return match ? [{name, number: Number(match[1])}] : [];
    }).sort((a, b) => a.number - b.number);
  for (const [i, part] of parts.entries()) {
    if (!Number.isSafeInteger(part.number) || part.number < 1 || parts[i - 1]?.number === part.number) {
      throw new Error("Invalid or duplicate part number: " + path.join(folder, part.name));
    }
  }
  return parts;
}

function writeGenerated(file, lines) {
  const content = "// Generated by the storytelling scaffolder.\n" + lines.join("\n") + "\n";
  if (fs.existsSync(file) && fs.readFileSync(file, "utf8") === content) return;
  const tmp = file + "." + randomUUID() + ".tmp";
  try {
    fs.writeFileSync(tmp, content);
    fs.renameSync(tmp, file);
  } finally {
    fs.rmSync(tmp, {force: true});
  }
}

export function refreshRegistry(rootDir) {
  const base = path.join(rootDir, "src/topics");
  const topics = directories(base).filter(topic => fs.existsSync(path.join(base, topic, "topic.config.ts")));
  const imports = [];
  const topicNames = [];
  for (const [t, topic] of topics.entries()) {
    validateSlug(topic, "topic");
    const topicDir = path.join(base, topic);
    const episodesDir = path.join(topicDir, "episodes");
    const episodeImports = [];
    const episodes = [];
    for (const slug of directories(episodesDir)) {
      const dir = path.join(episodesDir, slug);
      if (!fs.existsSync(path.join(dir, "Episode.tsx"))) continue;
      validateSlug(slug, "episode");
      const parts = partFiles(dir);
      writeGenerated(path.join(dir, "parts.generated.ts"), [
        'import type {PartComponents} from "@engine/episode/episode.types";',
        ...parts.map(p => `import Part${p.number} from "./parts/${p.name.slice(0, -4)}";`),
        "export const parts: PartComponents = {",
        ...parts.map(p => `  "${String(p.number).padStart(2,"0")}": Part${p.number},`), "};",
      ]);
      const i = episodes.length;
      episodeImports.push(`import {Episode as Episode${i}} from "./episodes/${slug}/Episode";`,
        `import data${i} from "./episodes/${slug}/episode.data.json";`);
      episodes.push(`  {slug: "${slug}", data: data${i}, component: Episode${i}},`);
    }
    writeGenerated(path.join(topicDir, "episodes.generated.ts"), [
      ...episodeImports, "export const episodes = [", ...episodes, "];",
    ]);
    imports.push(`import topic${t} from "./${topic}/topic.config";`);
    topicNames.push("topic" + t);
  }
  writeGenerated(path.join(base, "index.ts"), [
    'import type {TopicDefinition} from "@engine/episode/episode.types";',
    ...imports, `export const TOPICS: TopicDefinition[] = [${topicNames.join(", ")}];`,
  ]);
}
